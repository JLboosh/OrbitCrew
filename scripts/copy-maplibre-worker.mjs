/**
 * Publishes MapLibre's web worker into `public/` so the browser can load it.
 *
 * WHY THIS IS NECESSARY
 * --------------------
 * maplibre-gl finds its own worker with
 *
 *   new URL('./maplibre-gl-worker.mjs', import.meta.url)
 *
 * and gives up (returning an empty string) unless `import.meta.url` is an http
 * URL. Under Metro — which rewrites every module and does not hand out real file
 * URLs — that check fails, so MapLibre calls `new Worker('')`. The browser
 * resolves that to the current page, the dev server answers with index.html, and
 * the worker dies with "Failed to load module script: non-JavaScript MIME type".
 * The map then renders a blank canvas: no tiles are ever parsed, and `load` never
 * fires.
 *
 * The library's own escape hatch is `setWorkerUrl()`, which needs the worker
 * served at a stable path. That is what this script arranges, and
 * `GymMapView.web.tsx` points at it.
 *
 * WHY COPY INSTEAD OF COMMITTING THE FILES
 * ---------------------------------------
 * They are build output of a pinned dependency. Committed, they would silently go
 * stale on the next maplibre-gl bump and produce a worker/main-thread version
 * mismatch, which fails in confusing ways. Generated on install, they cannot
 * drift: the version is asserted below.
 *
 * The `.mjs` extension is dropped on the way out. Static file servers reliably
 * serve `.js` as JavaScript; `.mjs` is inconsistent, and a wrong Content-Type is
 * the exact failure mode we are fixing. The worker's one internal import is
 * rewritten to match.
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'maplibre');

/** Must match the path used by `setWorkerUrl` in GymMapView.web.tsx. */
const PUBLIC_PATH = '/maplibre/maplibre-gl-worker.js';

function main() {
  const pkg = require('maplibre-gl/package.json');
  const distDir = dirname(require.resolve('maplibre-gl/dist/maplibre-gl.mjs'));

  mkdirSync(OUT_DIR, { recursive: true });

  // The worker imports the shared chunk relatively, so both must land in the same
  // directory, and both must be renamed consistently.
  const worker = readFileSync(join(distDir, 'maplibre-gl-worker.mjs'), 'utf8');

  if (!worker.includes('./maplibre-gl-shared.mjs')) {
    console.error(
      'maplibre-gl worker no longer imports ./maplibre-gl-shared.mjs.\n' +
        'The layout of its dist output changed — re-check scripts/copy-maplibre-worker.mjs\n' +
        'against the installed version before trusting the map.',
    );
    process.exit(1);
  }

  writeFileSync(
    join(OUT_DIR, 'maplibre-gl-worker.js'),
    worker.replaceAll('./maplibre-gl-shared.mjs', './maplibre-gl-shared.js'),
  );
  copyFileSync(join(distDir, 'maplibre-gl-shared.mjs'), join(OUT_DIR, 'maplibre-gl-shared.js'));

  // Recorded so a stale copy is obvious rather than mysterious.
  writeFileSync(
    join(OUT_DIR, 'VERSION'),
    `maplibre-gl ${pkg.version}\ngenerated by scripts/copy-maplibre-worker.mjs\n`,
  );

  console.log(`maplibre-gl ${pkg.version} worker published at ${PUBLIC_PATH}`);
}

main();
